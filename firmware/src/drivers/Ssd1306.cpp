bool Ssd1306::command(uint8_t value) {
  wire_.beginTransmission(address_);
  wire_.write(static_cast<uint8_t>(0x00));
  wire_.write(value);
  return wire_.endTransmission() == 0;
}

bool Ssd1306::begin() {
  wire_.beginTransmission(address_);
  if (wire_.endTransmission() != 0) {
    online_ = false;
    return false;
  }

  const uint8_t init[] = {
    0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
    0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12,
    0x81, 0x8F, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6,
    0x2E, 0xAF
  };
  online_ = true;
  for (uint8_t value : init) online_ = command(value) && online_;
  clear();
  display();
  return online_;
}

void Ssd1306::clear() { memset(buffer_, 0, sizeof(buffer_)); }

void Ssd1306::pixel(int16_t x, int16_t y, bool on) {
  if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
  uint8_t &cell = buffer_[x + (y / 8) * 128];
  const uint8_t mask = 1U << (y & 7);
  if (on) cell |= mask;
  else cell &= ~mask;
}

void Ssd1306::drawChar(int16_t x, int16_t y, char c, uint8_t scale) {
  uint8_t glyph[5]{};
  if (!findGlyph(c, glyph)) findGlyph('?', glyph);
  for (uint8_t col = 0; col < 6; ++col) {
    const uint8_t bits = col < 5 ? glyph[col] : 0;
    for (uint8_t row = 0; row < 8; ++row) {
      const bool on = bits & (1U << row);
      for (uint8_t dx = 0; dx < scale; ++dx)
        for (uint8_t dy = 0; dy < scale; ++dy)
          pixel(x + col * scale + dx, y + row * scale + dy, on);
    }
  }
}

void Ssd1306::drawText(int16_t x, int16_t y, const char *text, uint8_t scale) {
  if (!text || scale == 0) return;
  while (*text && x < 128) {
    drawChar(x, y, *text++, scale);
    x += 6 * scale;
  }
}

void Ssd1306::display() {
  // 每页分块发送，避免单次写入超过 Wire 缓冲区容量。
  if (!online_) return;
  const uint8_t commands[] = {0x21, 0, 127, 0x22, 0, 7};
  for (uint8_t value : commands) {
    if (!command(value)) { online_ = false; return; }
  }

  for (size_t offset = 0; offset < sizeof(buffer_); offset += 16) {
    wire_.beginTransmission(address_);
    wire_.write(static_cast<uint8_t>(0x40));
    wire_.write(buffer_ + offset, 16);
    if (wire_.endTransmission() != 0) { online_ = false; return; }
  }
}
