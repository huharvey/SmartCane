bool findGlyph(char c, uint8_t out[5]) {
  if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
  for (size_t i = 0; i < sizeof(FONT) / sizeof(FONT[0]); ++i) {
    if (static_cast<char>(pgm_read_byte(&FONT[i].c)) == c) {
      for (uint8_t j = 0; j < 5; ++j) out[j] = pgm_read_byte(&FONT[i].col[j]);
      return true;
    }
  }
  return false;
}
